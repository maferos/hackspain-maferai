#!/usr/bin/env python3
"""Put a UR10e on an overhead linear rail above the shelf-free MiniHannover bench.

Run from simulation/: python scripts/generate_rail_scene.py.
Needs the Menagerie models first: bash scripts/fetch_menagerie.sh.

Writes two generated files:

* ``assets/ur10e_2f85/ur10e_2f85.xml`` --- Menagerie's UR10e with a Robotiq
  2F-85 attached at its wrist flange, plus the eye-in-hand camera: the MJCF
  camera, a site the IK aims, and the modelled camera body from
  ``assets/wrist_camera/`` at exactly the same pose, so the scene shows the
  hardware the pictures come from. MJCF cannot attach a child model to a *site*
  of an already-attached model, so all of it has to be spliced into a copy of
  the arm rather than added from the scene file.
* ``models/minihannover_rail_scene.xml`` --- the open scene plus the gantry:
  two end posts, a beam along the bench, and a carriage on a slide joint that
  carries the arm.

Why a rail at all: the UR10e reaches 1.30 m, the widest in Menagerie, and the
bench is 6 x 2 m. One static base covers a 1.30 m disc, about a third of the
worktop; a base that slides along the 6 m axis covers all of it.

Why the rail sits where it does, all measured off the open scene:

* ``RAIL_Y`` at the back edge strip. The wall camera looks at the bench from
  -Y, so a gantry behind the glassware hides the back edge instead of the
  bottles. Everything the arm has to pick lives in y = -0.83 .. 0.03.
* ``BEAM_BOTTOM`` clears 1.30 m, the top of the two analytical balances that
  stand on that strip, by 60 mm.
* The arm base ends up 0.55 m above the worktop, about the height
  its own gripper works at, so the full 1.30 m stays available horizontally
  instead of being spent on the drop to the bench.
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import generate_open_vessels as open_vessels
import numpy as np

SIM = Path(__file__).resolve().parents[1]
MENAGERIE = SIM / 'third_party/mujoco_menagerie'
ARM_DIR = SIM / 'assets/ur10e_2f85'
GRIPPER_DIR = SIM / 'assets/robotiq_2f85_sensed'
BASE_SCENE = 'minihannover_open_scene.xml'
ROOM = SIM / 'assets/minihannover_open/lab_room.xml'
# Written beside the original so its ../labelled_bottles/... mesh paths still
# resolve; it is the same room with the dynamic vessels cut out of it.
DYNAMIC_ROOM = SIM / 'assets/minihannover_open/lab_room_dynamic.xml'
OUT_SCENE = SIM / 'models/minihannover_rail_scene.xml'
HEADER = '<!-- Generated by scripts/generate_rail_scene.py; do not edit by hand. -->\n'

# Bench, from assets/minihannover_open/bench.xml: 6 x 2 m worktop, top at 0.90.
BENCH_X = (-4.5, 1.5)
BENCH_Y = (-1.4, 0.6)
BENCH_TOP = 0.90

RAIL_Y = 0.30          # rail axis, on the back edge strip
BEAM_BOTTOM = 1.36     # underside of the beam; balances on that strip top out at 1.30
BEAM_HALF_Z = 0.04
BEAM_HALF_Y = 0.06
BEAM_OVERHANG = 0.40   # beam sticks out past each end of the bench
POST_HALF = 0.06
CARRIAGE_HALF = (0.16, 0.20, 0.05)
CARRIAGE_Y = 0.14      # carriage hangs off the bench side of the beam
ARM_BASE_DZ = 0.05     # arm base sits on the top face of the carriage plate

BEAM_Z = BEAM_BOTTOM + BEAM_HALF_Z
BEAM_HALF_X = (BENCH_X[1] - BENCH_X[0]) / 2 + BEAM_OVERHANG
BEAM_X = (BENCH_X[0] + BENCH_X[1]) / 2
POST_X = BEAM_HALF_X - POST_HALF - 0.02
# Travel: the carriage can stand over any point of the worktop and a little past
# each end, stopping short of the posts.
TRAVEL = BEAM_HALF_X - POST_HALF * 2 - CARRIAGE_HALF[0] - 0.08
ARM_BASE_Z = BEAM_Z + ARM_BASE_DZ

# Scan pose: hand pointing straight down, wrist about 0.45 m below the base, the
# arm folded toward -Y so it leans over the bench rather than the back wall.
SCAN_POSE = (-1.5708, -1.9199, 2.0944, -1.7453, -1.5708, 0.0)

# How many vessels stand on the bench in this scene, spread along it. The open
# scene the computer-vision work renders from keeps its full population; here
# the bench is cleared down to a handful so the manipulation case is simple to
# watch and to debug. All of them are free bodies that can be picked up.
#
# Twelve is the manipulation scene. Raising it makes the task harder, and the
# two jobs want different benches: at thirty the vision scan is a good test
# --- more targets, still 98 mm apart --- and the pipette starts clipping
# neighbours on the way in, 12 mm of mean tip error against 1.1 at twelve.
# Pass --vessels to regenerate at another count.
BENCH_VESSELS = 12

# Which tool hangs on the flange. 'pipette' is the pipetting scene; 'gripper'
# puts the Robotiq back for scripts/grasp_test.py.
TOOL = 'pipette'

# Which of the scene's five balances gets its roof cut off and takes the beaker.
# balance_5 stands at x = -0.75 on the back strip, the closest one to the rail.
OPEN_BALANCE = 'balance_5_'
BALANCE_PAN = (-0.005, 0.031, 0.077)    # pan centre in the balance's own frame
# and it moves here. Left where it stood on the back strip, the beaker's rim
# sits at 1.08 m, which puts the pipette's flange at 1.34 --- 20 mm under the
# gantry beam, with the whole wrist in the way. Out in front of the rail there
# is nothing overhead.
BALANCE_POS = (0.60, -0.45, BENCH_TOP)

# Eye-in-hand camera, in the tool frame (+Z is the approach direction).
EIH_OFFSET = 0.09   # to the side of the tool axis, clear of the fingers
EIH_DROP = 0.03     # below the flange: on the wrist, just under it
EIH_TILT = 0.0      # degrees of convergence toward the tool axis. Zero on
                    # purpose: the gripper sits ON that axis, so a converging
                    # camera aims straight at the back of its own fingers.
                    # Parallel puts the gripper at the frame edge instead and
                    # whatever the camera is aimed at in the middle.


def _fmt(vector) -> str:
    """Format a 3-vector for an MJCF attribute."""
    return ' '.join(f'{v:.4f}' for v in vector)


def build_gripper() -> Path:
    """Write a Robotiq 2F-85 that can feel what it is holding.

    Menagerie's gripper already behaves like the real one when it closes on
    something: the actuator is a position servo on a tendon with
    ``forcerange="-5 5"``, so the pads stall against the object and keep
    squeezing at the limit instead of crushing through it. What it has no way of
    doing is *reporting* that, and the scene has no sensors at all --- which
    leaves a grasp check with nothing to go on but the object's true height,
    which no real cell can see.

    This copy adds a touch site over each pad and the sensors that reconstruct
    the 2F-85's own object-detection status: how hard each pad is pressed, what
    the finger servo is putting out, and how far the fingers actually closed.
    Fingers stalled short of shut plus force on the pads is a held object;
    fingers all the way shut with no force is a closure on thin air.

    Returns:
        Path of the generated gripper MJCF.

    Raises:
        FileNotFoundError: If the Menagerie models have not been fetched.
    """
    source = MENAGERIE / 'robotiq_2f85/2f85.xml'
    if not source.exists():
        raise FileNotFoundError(
            f'{source} missing --- run: bash scripts/fetch_menagerie.sh')

    xml = source.read_text()
    xml = xml.replace(
        'meshdir="assets"',
        'meshdir="../../third_party/mujoco_menagerie/robotiq_2f85/assets"')
    # One site per finger, spanning both pad boxes, for the touch sensors.
    for side in ('right', 'left'):
        xml = xml.replace(
            f'<geom class="pad_box2" name="{side}_pad2"/>',
            f'<geom class="pad_box2" name="{side}_pad2"/>\n'
            f'              <site name="{side}_pad_touch" type="box"\n'
            f'                    pos="0 -0.0026 0.01875" size="0.013 0.006 0.021"\n'
            f'                    rgba="0.9 0.4 0.1 0.25" group="4"/>')
    xml = xml.replace('</mujoco>',
                      '  <sensor>\n'
                      '    <touch name="right_pad_force" site="right_pad_touch"/>\n'
                      '    <touch name="left_pad_force" site="left_pad_touch"/>\n'
                      '    <actuatorfrc name="finger_drive" actuator="fingers_actuator"/>\n'
                      '    <jointpos name="right_finger" joint="right_driver_joint"/>\n'
                      '    <jointpos name="left_finger" joint="left_driver_joint"/>\n'
                      '  </sensor>\n'
                      '</mujoco>')
    xml = xml.replace('<mujoco model="2f85">',
                      '<mujoco model="2f85_sensed">\n  ' + HEADER.strip())

    GRIPPER_DIR.mkdir(parents=True, exist_ok=True)
    out = GRIPPER_DIR / '2f85_sensed.xml'
    out.write_text(xml)
    return out


