#!/usr/bin/env python3
"""Put a UR10e on an overhead linear rail above the shelf-free MiniHannover bench.

Run from simulation/: python scripts/generate_rail_scene.py.
Needs the Menagerie models first: bash scripts/fetch_menagerie.sh.

Writes two generated files:

* ``assets/ur10e_2f85/ur10e_2f85.xml`` --- Menagerie's UR10e with a Robotiq
  2F-85 attached at its wrist flange, plus the eye-in-hand camera: the MJCF
  camera, a site the IK aims, and the modelled camera body from
  ``assets/wrist_camera/`` at exactly the same pose, so the scene shows the
  hardware the pictures come from. MJCF cannot attach a child model to a *site*
  of an already-attached model, so all of it has to be spliced into a copy of
  the arm rather than added from the scene file.
* ``models/minihannover_rail_scene.xml`` --- the open scene plus the gantry:
  two end posts, a beam along the bench, and a carriage on a slide joint that
  carries the arm.

Why a rail at all: the UR10e reaches 1.30 m, the widest in Menagerie, and the
bench is 6 x 2 m. One static base covers a 1.30 m disc, about a third of the
worktop; a base that slides along the 6 m axis covers all of it.

Why the rail sits where it does, all measured off the open scene:

* ``RAIL_Y`` at the back edge strip. The wall camera looks at the bench from
  -Y, so a gantry behind the glassware hides the back edge instead of the
  bottles. Everything the arm has to pick lives in y = -0.83 .. 0.03.
* ``BEAM_BOTTOM`` clears 1.30 m, the top of the two analytical balances that
  stand on that strip, by 60 mm.
* The arm base ends up 0.55 m above the worktop, about the height
  its own gripper works at, so the full 1.30 m stays available horizontally
  instead of being spent on the drop to the bench.
"""
