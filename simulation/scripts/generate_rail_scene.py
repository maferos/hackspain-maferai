                    # Parallel puts the gripper at the frame edge instead and
                    # whatever the camera is aimed at in the middle.


def _fmt(vector) -> str:
    """Format a 3-vector for an MJCF attribute."""
    return ' '.join(f'{v:.4f}' for v in vector)


def build_gripper() -> Path:
    """Write a Robotiq 2F-85 that can feel what it is holding.

    Menagerie's gripper already behaves like the real one when it closes on
    something: the actuator is a position servo on a tendon with
    ``forcerange="-5 5"``, so the pads stall against the object and keep
    squeezing at the limit instead of crushing through it. What it has no way of
    doing is *reporting* that, and the scene has no sensors at all --- which
    leaves a grasp check with nothing to go on but the object's true height,
    which no real cell can see.

    This copy adds a touch site over each pad and the sensors that reconstruct
    the 2F-85's own object-detection status: how hard each pad is pressed, what
    the finger servo is putting out, and how far the fingers actually closed.
    Fingers stalled short of shut plus force on the pads is a held object;
    fingers all the way shut with no force is a closure on thin air.

    Returns:
        Path of the generated gripper MJCF.

    Raises:
        FileNotFoundError: If the Menagerie models have not been fetched.
    """
    source = MENAGERIE / 'robotiq_2f85/2f85.xml'
    if not source.exists():
        raise FileNotFoundError(
            f'{source} missing --- run: bash scripts/fetch_menagerie.sh')

    xml = source.read_text()
    xml = xml.replace(
        'meshdir="assets"',
        'meshdir="../../third_party/mujoco_menagerie/robotiq_2f85/assets"')
    # One site per finger, spanning both pad boxes, for the touch sensors.
    for side in ('right', 'left'):
        xml = xml.replace(
            f'<geom class="pad_box2" name="{side}_pad2"/>',
            f'<geom class="pad_box2" name="{side}_pad2"/>\n'
            f'              <site name="{side}_pad_touch" type="box"\n'
            f'                    pos="0 -0.0026 0.01875" size="0.013 0.006 0.021"\n'
            f'                    rgba="0.9 0.4 0.1 0.25" group="4"/>')
    xml = xml.replace('</mujoco>',
                      '  <sensor>\n'
                      '    <touch name="right_pad_force" site="right_pad_touch"/>\n'
                      '    <touch name="left_pad_force" site="left_pad_touch"/>\n'
                      '    <actuatorfrc name="finger_drive" actuator="fingers_actuator"/>\n'
                      '    <jointpos name="right_finger" joint="right_driver_joint"/>\n'
                      '    <jointpos name="left_finger" joint="left_driver_joint"/>\n'
                      '  </sensor>\n'
                      '</mujoco>')
    xml = xml.replace('<mujoco model="2f85">',
                      '<mujoco model="2f85_sensed">\n  ' + HEADER.strip())

    GRIPPER_DIR.mkdir(parents=True, exist_ok=True)
    out = GRIPPER_DIR / '2f85_sensed.xml'
    out.write_text(xml)
    return out


