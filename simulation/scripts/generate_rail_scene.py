def build_arm() -> Path:
    """Write the UR10e + Robotiq 2F-85 model used by the scene.

    Returns:
        Path of the generated arm MJCF.

    Raises:
        FileNotFoundError: If the Menagerie models have not been fetched.
    """
    source = MENAGERIE / 'universal_robots_ur10e/ur10e.xml'
    if not source.exists():
        raise FileNotFoundError(
            f'{source} missing --- run: bash scripts/fetch_menagerie.sh')

    xml = source.read_text()
    # A thin visual-only wrap on both sides of the upper arm. Keep the supplied
    # vector wordmark in assets/branding; UVs preserve its original proportions.
    vertices, uv, faces = [], [], []
    segments = 32
    for i in range(segments + 1):
        v = i / segments
        angle = (v - 0.5) * (0.28 * 350 / 1540) / 0.061
        for u in (0, 1):
            vertices.extend((0.061 * np.sin(angle),
                             -0.061 * np.cos(angle), 0.3065 + (u - 0.5) * 0.28))
            uv.extend((1 - u, 1 - v))
    for i in range(segments):
        a = 2 * i
        faces.extend((a, a + 2, a + 1, a + 1, a + 2, a + 3))
    xml = xml.replace('<asset>', '<asset>\n'
        '    <texture name="mafer_logo" type="2d" file="../branding/mafer-label.png"/>\n'
        '    <material name="mafer_label" texture="mafer_logo" specular="0.1" shininess="0.1"/>\n'
        f'    <mesh name="mafer_wrap" vertex="{_fmt(vertices)}" '
        f'texcoord="{_fmt(uv)}" face="{" ".join(map(str, faces))}"/>', 1)
    anchor = '<geom mesh="upperarm_3" material="linkgray" class="visual"/>'
    xml = xml.replace(anchor, anchor + '\n'
        '          <geom name="mafer_front" mesh="mafer_wrap" material="mafer_label" class="visual" mass="0"/>\n'
        '          <geom name="mafer_back" mesh="mafer_wrap" material="mafer_label" class="visual" mass="0" quat="0 0 0 1"/>')
    rel = '../../third_party/mujoco_menagerie'
    xml = xml.replace('meshdir="assets"',
                      f'meshdir="{rel}/universal_robots_ur10e/assets"')
    xml = xml.replace(
        '<asset>',
        '<asset>\n'
        + ('    <model name="robotiq_2f85" file="../robotiq_2f85_sensed/2f85_sensed.xml"/>\n'
           if TOOL == 'gripper' else
           '    <model name="pipette" file="../pipette/pipette.xml"/>\n')
        + '    <model name="wrist_camera" file="../wrist_camera/wrist_camera.xml"/>',
        1)
    # The flange site is where UR documents the tool frame; put the gripper on it,
    # and the eye-in-hand camera beside it. Both live in a frame whose +Z is the
    # tool's approach direction.
    #
    # The camera sits EIH_OFFSET to the side and EIH_DROP below the flange --- on
    # the wrist, just under it, clear of the fingers --- looking EIH_TILT off the
    # tool axis. A MuJoCo camera looks along its own -Z; `eih_site` is the same
    # pose with +Z along the view instead, which is what solve_ik expects.
    view = np.array([-np.sin(np.radians(EIH_TILT)), 0.0,
                     np.cos(np.radians(EIH_TILT))])
    up = np.cross(-view, (0.0, 1.0, 0.0))
    xml = xml.replace(
        '<site name="attachment_site" pos="0 0.1 0" quat="-1 1 0 0"/>',
        '<site name="attachment_site" pos="0 0.1 0" quat="-1 1 0 0"/>\n'
        '                  <frame pos="0 0.1 0" quat="-1 1 0 0">\n'
        + ('                    <attach model="robotiq_2f85" body="base_mount" prefix="grip_"/>\n'
           if TOOL == 'gripper' else
           '                    <attach model="pipette" body="pipette" prefix="pip_"/>\n')
        +
        f'                    <camera name="eih" pos="{EIH_OFFSET} 0 {EIH_DROP}"\n'
        f'                            xyaxes="0 1 0 {_fmt(up)}"\n'
        '                            fovy="60.44" resolution="1920 1080"/>\n'
        f'                    <site name="eih_site" pos="{EIH_OFFSET} 0 {EIH_DROP}"\n'
        f'                          xyaxes="0 1 0 {_fmt(-up)}" size="0.004" group="4"/>\n'
        f'                    <frame pos="{EIH_OFFSET} 0 {EIH_DROP}"\n'
        f'                           xyaxes="0 1 0 {_fmt(-up)}">\n'
        '                      <attach model="wrist_camera" body="wrist_camera"\n'
        '                              prefix="cam_"/>\n'
        '                    </frame>\n'
        '                  </frame>')
    # Gravity compensation on the arm links. Menagerie's stock position gains
    # leave about 20 mm of droop at the tool under gravity, which is more than
    # the radius of a 20 ml flask --- the gripper closes off-centre and catches
    # the vessel with one pad instead of pinching it. Compensating gravity
    # leaves the servos only inertia to fight. The payload is deliberately not
    # compensated: a held vessel should still weigh something.
    xml = re.sub(r'<body name="(base|shoulder_link|upper_arm_link|forearm_link|'
                 r'wrist_1_link|wrist_2_link|wrist_3_link)"',
                 r'<body gravcomp="1" name="\1"', xml)
    # The arm's own keyframe no longer matches nq once the gripper is on, and the
    # scene sets poses from Python anyway.
    xml = re.sub(r'\n  <keyframe>.*?</keyframe>', '', xml, flags=re.DOTALL)
    xml = xml.replace('<mujoco model="ur10e">',
                      '<mujoco model="ur10e_2f85">\n  ' + HEADER.strip())

    ARM_DIR.mkdir(parents=True, exist_ok=True)
    out = ARM_DIR / 'ur10e_2f85.xml'
    out.write_text(xml)
    return out


def build_bench(keep: int) -> list[dict[str, str]]:
    """Clear the bench down to `keep` vessels, and hand them to the scene.

    The bench population is baked into the room model as static geometry: five
    geoms per vessel, one of them a collision cylinder. That makes every vessel
    an obstacle and none of them an object --- no body, no joint, no mass, so a
    closed gripper slides straight through the pose. Vessels that need to be
    picked up have to become bodies with a free joint in the *scene*, because
    MuJoCo only allows a free joint on a child of the world, and the room is
    attached as a body.

    Everything not kept is deleted rather than left standing, so the survivors
    have room for the fingers. The open scene keeps its full population; this
    only thins the copy the rail scene loads.

    Each catalogued sample already exists as its own model under
    assets/labelled_bottles/, which is how the scene's seven loose vessels are
    built, so the scene re-adds them the same way rather than rebuilding the
    geometry.

    Args:
        count: How many vessels to lift, spread along the bench.

    The static geoms are nested inside the room's sub-bodies, so their ``pos``
    attributes are not world coordinates. The pose to re-create each vessel at
    is read from the compiled base scene instead, where MuJoCo has already
    composed the whole chain.

    Returns:
        One dict per lifted vessel with its sample id, world position and yaw.
    """
    tree = ET.parse(ROOM)
    # The population is nested inside the room's sub-bodies, so walk the whole
    # tree and keep a parent map: ElementTree has no parent pointers and the
    # geoms have to be removed from wherever they actually live.
    parent_of = {child: parent for parent in tree.getroot().iter()
                 for child in parent}
    vessels: dict[str, list[ET.Element]] = {}
    for geom in list(tree.getroot().iter('geom')):
        # Keep the wash-zone balance clear in the rail scene.
        if geom.get('name') == 'funnel_0':
            parent_of[geom].remove(geom)
            continue
        match = re.match(r'stock_(.+?)_(?:glass|cap|label|label_back|collision)',
                         geom.get('name', ''))
        if match:
            vessels.setdefault(match.group(1), []).append(geom)

    # Only catalogued samples have a model of their own to re-attach; the
    # unbarcoded reserve stock is scenery either way, so it always goes.
    catalogued = [s for s in vessels
                  if (SIM / f'assets/labelled_bottles/{s}.xml').exists()]
    ordered = sorted(catalogued,
                     key=lambda k: float(vessels[k][0].get('pos').split()[0]))
    step = max(len(ordered) // max(keep, 1), 1)
    picked = ordered[::step][:keep]

    import mujoco

    base = mujoco.MjModel.from_xml_path(str(SIM / 'models' / BASE_SCENE))
    state = mujoco.MjData(base)
    mujoco.mj_forward(base, state)

    for sample, geoms in vessels.items():
        if sample in picked:
            continue
        for geom in geoms:
            parent_of[geom].remove(geom)

    lifted = []
    for sample in picked:
        geoms = vessels[sample]
        # A mesh geom's xpos is the mesh's own centre, because the compiler
        # re-centres mesh vertices and records the shift in mesh_pos. Undoing
        # that shift recovers the authored origin --- the vessel's bottom
        # centre, which is the frame the per-sample model under
        # assets/labelled_bottles/ is built in.
        placed = state.geom(f'room_stock_{sample}_glass_0')
        rotation = placed.xmat.reshape(3, 3)
        shift = base.mesh_pos[base.geom_dataid[base.geom(f'room_stock_{sample}_glass_0').id]]
        origin = placed.xpos - rotation @ shift
        yaw = np.degrees(np.arctan2(rotation[1, 0], rotation[0, 0]))
        lifted.append({'sample': sample,
                       'pos': ' '.join(f'{v:.6g}' for v in origin),
                       'euler': f'0 0 {yaw:.6g}'})
        for geom in geoms:
            parent_of[geom].remove(geom)

    ET.indent(tree.getroot(), space='  ')
    DYNAMIC_ROOM.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER
        + ET.tostring(tree.getroot(), encoding='unicode') + '\n')
    return lifted


def build_scene() -> Path:
    """Write the rail scene: the open bench scene plus the gantry and the arm.

    The base scene is spliced in rather than ``<include>``d: MuJoCo resolves the
    asset paths of an included file against the *including* file's directory,
    which breaks the ``../assets/...`` references. Both files sit in models/, so
    copying the tree over keeps every path valid.

    Returns:
        Path of the generated scene MJCF.
    """
    tree = ET.parse(SIM / 'models' / BASE_SCENE)
    root = tree.getroot()
    root.set('model', 'minihannover_rail_scene')

    # The gripper wants elliptic friction cones, the arm wants implicitfast.
    ET.SubElement(root, 'option', integrator='implicitfast', impratio='10',
                  cone='elliptic')

    asset = root.find('asset')
    ET.SubElement(asset, 'material', name='gantry', rgba='0.42 0.44 0.48 1',
                  specular='0.4', shininess='0.5')
    ET.SubElement(asset, 'material', name='carriage', rgba='0.22 0.24 0.28 1',
                  specular='0.5', shininess='0.6')
    ET.SubElement(asset, 'model', name='ur10e_2f85',
                  file='../assets/ur10e_2f85/ur10e_2f85.xml')

    # Swap the room for the one without the vessels the scene now owns, and
    # declare each of those as its own model.
    lifted = build_bench(BENCH_VESSELS)
    asset.find('model[@name="lab_room"]').set(
        'file', f'../{DYNAMIC_ROOM.relative_to(SIM)}')
    open_vessels.main_for([v['sample'] for v in lifted])
    for vessel in lifted:
        ET.SubElement(asset, 'model', name=f'dyn_{vessel["sample"]}',
                      file=f'../assets/open_vessels/{vessel["sample"]}.xml')
    if TOOL == 'pipette':
        ET.SubElement(asset, 'model', name='beaker',
                      file='../assets/beaker/beaker.xml')
        ET.SubElement(asset, 'model', name='balance_open',
                      file='../assets/balance_open/balance_open.xml')

    world = root.find('worldbody')
    for vessel in lifted:
        body = ET.SubElement(world, 'body', name=f'dyn_{vessel["sample"]}',
                             pos=vessel['pos'], euler=vessel['euler'])
        ET.SubElement(body, 'freejoint')
        ET.SubElement(body, 'attach', model=f'dyn_{vessel["sample"]}',
                      body=vessel['sample'], prefix=f'dyn_{vessel["sample"]}_')
    if TOOL == 'pipette':
        # One balance loses its roof and gains a pan; the beaker stands on it.
        frame = next(f for f in world.iter('frame')
                     if any(a.get('prefix') == OPEN_BALANCE
                            for a in f.findall('attach')))
        frame.find('attach').set('model', 'balance_open')
        frame.set('pos', ' '.join(f'{v:g}' for v in BALANCE_POS))
        frame.attrib.pop('euler', None)
        base = list(BALANCE_POS)
        beaker = ET.SubElement(
            world, 'body', name='beaker',
            pos=' '.join(f'{base[i] + BALANCE_PAN[i]:.5g}' for i in range(3)))
        ET.SubElement(beaker, 'freejoint')
        ET.SubElement(beaker, 'attach', model='beaker', body='beaker',
                      prefix='beaker_')

    post_z = BEAM_BOTTOM / 2
    rail = ET.SubElement(world, 'body', name='rail')
    for side, x in (('left', BEAM_X - POST_X), ('right', BEAM_X + POST_X)):
        ET.SubElement(rail, 'geom', name=f'rail_post_{side}', type='box',
                      material='gantry', pos=f'{x:.3f} {RAIL_Y} {post_z:.3f}',
                      size=f'{POST_HALF} {POST_HALF} {post_z:.3f}')
    ET.SubElement(rail, 'geom', name='rail_beam', type='box', material='gantry',
                  pos=f'{BEAM_X} {RAIL_Y} {BEAM_Z:.3f}',
                  size=f'{BEAM_HALF_X:.3f} {BEAM_HALF_Y} {BEAM_HALF_Z}')

    carriage = ET.SubElement(world, 'body', name='rail_carriage',
                             pos=f'{BEAM_X} {CARRIAGE_Y} {BEAM_Z:.3f}')
    ET.SubElement(carriage, 'joint', name='rail_x', type='slide', axis='1 0 0',
                  range=f'{-TRAVEL:.3f} {TRAVEL:.3f}', damping='200',
                  armature='20')
    ET.SubElement(carriage, 'geom', name='rail_carriage_plate', type='box',
                  material='carriage', mass='40', contype='0', conaffinity='0',
                  size=' '.join(str(h) for h in CARRIAGE_HALF))
    frame = ET.SubElement(carriage, 'frame', pos=f'0 0 {ARM_BASE_DZ}')
    ET.SubElement(frame, 'attach', model='ur10e_2f85', body='base',
                  prefix='arm_')
    # Rides with the arm, looking down the bench from behind the carriage.
    ET.SubElement(carriage, 'camera', name='carriage', pos='0 -0.9 0.75',
                  xyaxes='1 0 0 0 0.6 0.8', fovy='60.44',
                  resolution='1920 1080')

    actuator = ET.SubElement(root, 'actuator')
    ET.SubElement(actuator, 'position', name='rail_x', joint='rail_x',
                  kp='60000', kv='6000', forcerange='-4000 4000',
                  ctrlrange=f'{-TRAVEL:.3f} {TRAVEL:.3f}')

    keyframe = ET.SubElement(root, 'keyframe')
    # Rail, the six arm joints, and the gripper's finger drive when it is on.
    pose = ' '.join(f'{q:.4f}' for q in SCAN_POSE)
    tail = ' 0' if TOOL == 'gripper' else ''
    ET.SubElement(keyframe, 'key', name='scan', ctrl=f'0 {pose}{tail}')

    ET.indent(root, space='  ')
    OUT_SCENE.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER
                         + ET.tostring(root, encoding='unicode') + '\n')
    return OUT_SCENE


def check_camera_clearance() -> float:
    """Confirm no part of the modelled camera can appear in its own picture.

    The camera body is placed relative to the lens front, so a change to either
    the mount offsets or the model can quietly push hardware in front of the
    lens, where it shows up as a black crescent on every frame. Cheap to assert
    here instead.

    Returns:
        The clearance in metres: how far the frontmost camera part sits behind
        the viewpoint.

    Raises:
        AssertionError: If anything sits in front of it.
    """
    import mujoco

    model = mujoco.MjModel.from_xml_path(str(OUT_SCENE))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    camera = model.camera('arm_eih').id
    view = -data.cam_xmat[camera].reshape(3, 3)[:, 2]
    worst, worst_name = -np.inf, ''
    for i in range(model.ngeom):
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, i) or ''
        if not name.startswith('arm_cam_'):
            continue
        # Frontmost corner of the geom's own bounding box, which is tight for
        # the boxes and cylinders this camera is made of.
        centre, half = model.geom_aabb[i][:3], model.geom_aabb[i][3:]
        signs = np.array([[sx, sy, sz] for sx in (-1, 1) for sy in (-1, 1)
                          for sz in (-1, 1)])
        corners = ((signs * half + centre)
                   @ data.geom_xmat[i].reshape(3, 3).T + data.geom_xpos[i])
        front = float(np.dot(corners - data.cam_xpos[camera], view).max())
        if front > worst:
            worst, worst_name = front, name
    assert worst < 0, f'{worst_name} sticks {worst * 1000:.1f} mm into the view'
    return -worst


