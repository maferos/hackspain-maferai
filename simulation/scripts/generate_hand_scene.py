#!/usr/bin/env python3
"""The UR10e hand picking up an amber bottle, for MuJoCo and for Isaac.

Run from simulation/: python scripts/generate_hand_scene.py.
Then play it: python scripts/hand_pick.py (MuJoCo) or
scripts/hand_pick_isaac.py (Isaac Lab).

One kinematic description, two formats, the way ``assets/minihannover`` ships
MJCF and URDF side by side:

* ``assets/ur10e_hand/ur10e_hand.xml`` --- the hand as an attachable MJCF: the
  arm stub, ``wrist_3_joint`` with the flange, and the Robotiq 2F-85 from
  ``assets/robotiq_2f85_sensed/``. The same two degrees of freedom as
  ``ur10e_hand.blend``: the wrist roll and the gripper.
* ``models/hand_pick_scene.xml`` --- the MuJoCo scene: a floor, the 60 ml amber
  bottle with the white cap from ``assets/amber_bottles/`` loose on it, and the
  hand held out sideways from a two-axis carriage (``reach`` along X,
  ``lift`` along Z) so it can come to the bottle.
* ``models/hand_pick_rig.urdf`` and ``assets/amber_bottles/amber_060ml.urdf``
  --- the same carriage, hand and bottle for Isaac's URDF importer.

The one real difference between the two: the 2F-85's fingers are closed
four-bar linkages, which MuJoCo closes with ``<connect>`` equalities and a URDF
cannot express at all. The URDF opens each loop at the coupler (whose joint
stays within a milliradian of zero over the whole stroke, so it is made fixed)
and slaves every other finger joint to ``right_driver_joint`` with a ``mimic``
tag. The ratios are fitted here from MuJoCo's own solution of the linkage; the
fit has to hold to 0.01 rad over the stroke or the script stops. Only the pads
collide in the URDF, as boxes, which is also what grips in MuJoCo.

Frames: the hand is in the tool frame of the arm (origin on the flange face,
+Z the approach). The carriage holds it for a side grasp: the fingers point
along +X, tilted ``APPROACH_TILT`` below the horizontal (hand_pick_plan.py),
and open and close along world Y. The carriage's joints read in world terms:
``reach`` is the flange's world X, ``lift`` its world Z.
"""
import math

import mujoco
import numpy as np

import hand_pick_plan as plan
from hand_linkage import (GRIPPER, MATERIALS, MESH_MATERIAL, OUT_DIR,
                          RING_HEIGHT, SIM, STUB_LENGTH, STUB_RADIUS, STUB_TOP,
                          gripper_bodies, sweep_linkage, wrist3_pose)

HAND_XML = OUT_DIR / 'ur10e_hand.xml'
SCENE_XML = SIM / 'models/hand_pick_scene.xml'
RIG_URDF = SIM / 'models/hand_pick_rig.urdf'
BOTTLE_DIR = SIM / 'assets/amber_bottles'
BOTTLE = 'amber_060ml'
BOTTLE_URDF = BOTTLE_DIR / f'{BOTTLE}.urdf'

# wrist_3_link's inertial in the arm MJCF (Menagerie's ur10e.xml).
WRIST3_MASS = 0.202
WRIST3_IPOS = np.array([0.0, 0.092, 0.0])
WRIST3_IQUAT = np.array([0.0, 1.0, -1.0, 0.0]) / np.sqrt(2)
WRIST3_INERTIA = (0.000204525, 0.000144346, 0.000144346)
STUB_MASS = 1.0              # the stand-in cylinder; it rides the carriage
CARRIAGE_MASS = 1.0          # each of the reach and lift links

ACTUATED = 'right_driver_joint'
REACH_RANGE = (-0.5, 0.5)
LIFT_RANGE = (0.0, 0.6)
HOME = {'reach': plan.HOME_REACH, 'lift': plan.HOME_LIFT}
BOTTLE_POS = (*plan.BOTTLE_XY, 0.0)

HEADER = 'Generated by scripts/generate_hand_scene.py; do not edit by hand.'


def num(x) -> str:
    """A number for XML, short and without a negative zero."""
    return f'{float(x) + 0.0:.6g}'


def vec(v) -> str:
    return ' '.join(num(x) for x in v)


def rpy(quat) -> np.ndarray:
    """URDF roll-pitch-yaw (fixed X, Y, Z) of a MuJoCo (w, x, y, z) quaternion."""
    m = np.zeros(9)
    mujoco.mju_quat2Mat(m, np.asarray(quat, float) / np.linalg.norm(quat))
    r = m.reshape(3, 3)
    if abs(r[2, 0]) > 1 - 1e-9:
        # Gimbal lock, pitch straight up or down: roll and yaw are one angle;
        # put it all in roll (e.g. the tool frame turned back onto the hand).
        sign = -math.copysign(1.0, r[2, 0])
        return np.array([math.atan2(sign * r[0, 1], sign * r[0, 2]), sign * math.pi / 2, 0.0])
    return np.array([math.atan2(r[2, 1], r[2, 2]),
                     math.asin(max(-1.0, min(1.0, -r[2, 0]))),
                     math.atan2(r[1, 0], r[0, 0])])


def rotate(quat, v) -> np.ndarray:
    out = np.zeros(3)
    mujoco.mju_rotVecQuat(out, np.asarray(v, float), np.asarray(quat, float))
    return out


def hand_mount_quat() -> np.ndarray:
    """The tool frame on the carriage: approach (+Z) along +X, tilted down by
    APPROACH_TILT; the fingers' spread (+X) along world +Y."""
    a = plan.APPROACH_TILT
    x, z = np.array([0.0, 1.0, 0.0]), np.array([np.cos(a), 0.0, -np.sin(a)])
    quat = np.zeros(4)
    mujoco.mju_mat2Quat(quat, np.column_stack([x, np.cross(z, x), z]).ravel())
    return quat


def wrist3_inertial() -> tuple[np.ndarray, np.ndarray]:
    """wrist_3_link's inertial frame, moved from its link frame to the tool frame."""
    to_tool_pos, to_tool_quat = wrist3_pose()
    pos, quat = np.zeros(3), np.zeros(4)
    mujoco.mju_mulPose(pos, quat, to_tool_pos, to_tool_quat,
                       WRIST3_IPOS, WRIST3_IQUAT)
    return pos, quat


def mimic_ratios() -> dict[str, float]:
    """Each finger joint as a multiple of the actuated driver joint.

    Raises:
        RuntimeError: If a joint strays from its linear fit by more than
            0.01 rad anywhere in the stroke, or has an offset worth keeping.
    """
    _, angles = sweep_linkage()
    driver = angles[ACTUATED]
    ratios = {}
    for name, q in angles.items():
        slope, offset = np.polyfit(driver, q, 1)
        error = np.abs(np.polyval((slope, offset), driver) - q).max()
        if error > 0.01 or abs(offset) > 0.005:
            raise RuntimeError(f'{name}: not linear in {ACTUATED} '
                               f'(off by {error:.4f} rad, offset {offset:.4f})')
        ratios[name] = 0.0 if abs(slope) < 0.01 else round(float(slope), 4)
    return ratios


