# --- URDF --------------------------------------------------------------------


def inertial_xml(mass, pos, quat, diag, indent='    ') -> str:
    mass = max(float(mass), 1e-3)
    diag = [max(float(d), 1e-7) for d in diag]
    return (f'{indent}<inertial>\n'
            f'{indent}  <origin xyz="{vec(pos)}" rpy="{vec(rpy(quat))}"/>\n'
            f'{indent}  <mass value="{num(mass)}"/>\n'
            f'{indent}  <inertia ixx="{num(diag[0])}" ixy="0" ixz="0" iyy="{num(diag[1])}"'
            f' iyz="0" izz="{num(diag[2])}"/>\n'
            f'{indent}</inertial>\n')


def mesh_visual(filename, material, pos=(0, 0, 0), quat=(1, 0, 0, 0), scale=1.0) -> str:
    return ('    <visual>\n'
            f'      <origin xyz="{vec(pos)}" rpy="{vec(rpy(quat))}"/>\n'
            f'      <geometry><mesh filename="{filename}" scale="{vec([scale] * 3)}"/></geometry>\n'
            f'      <material name="{material}"/>\n'
            '    </visual>\n')


def joint_xml(name, kind, parent, child, pos=(0, 0, 0), quat=(1, 0, 0, 0), axis=None,
              limit=None, effort=100.0, velocity=1.0, mimic=None) -> str:
    out = (f'  <joint name="{name}" type="{kind}">\n'
           f'    <parent link="{parent}"/>\n    <child link="{child}"/>\n'
           f'    <origin xyz="{vec(pos)}" rpy="{vec(rpy(quat))}"/>\n')
    if axis is not None:
        out += f'    <axis xyz="{vec(axis)}"/>\n'
    if limit is not None:
        out += (f'    <limit lower="{num(limit[0])}" upper="{num(limit[1])}"'
                f' effort="{num(effort)}" velocity="{num(velocity)}"/>\n')
    if mimic is not None:
        out += f'    <mimic joint="{mimic[0]}" multiplier="{num(mimic[1])}" offset="0"/>\n'
    return out + '  </joint>\n'


def gripper_urdf(model, ratios: dict[str, float], parent: str, links: list[str], joints: list[str]) -> None:
    """Append the 2F-85 to a URDF, body by body, hanging off `parent`.

    A link frame sits on its joint's axis, so a body whose joint is off its
    origin (the followers) is shifted by jpos. Every finger joint mimics
    ACTUATED with its fitted ratio; the couplers, which the linkage keeps at
    zero, are fixed. Only the pad boxes collide.
    """
    grip_dir = '../third_party/mujoco_menagerie/robotiq_2f85/assets'
    names = {0: parent}
    shift = {0: np.zeros(3)}
    for b, name, parent_id, pos, quat, joint, jpos, meshes in gripper_bodies(model):
        names[b], shift[b] = name, jpos
        origin = pos + rotate(quat, jpos) - shift[parent_id]
        body = ''.join(mesh_visual(f'{grip_dir}/{m}.stl', MESH_MATERIAL[m], -jpos, scale=0.001)
                       for m in meshes)
        for g in range(model.body_geomadr[b], model.body_geomadr[b] + model.body_geomnum[b]):
            if model.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX:
                body += ('    <collision>\n'
                         f'      <origin xyz="{vec(model.geom_pos[g] - jpos)}" rpy="{vec(rpy(model.geom_quat[g]))}"/>\n'
                         f'      <geometry><box size="{vec(2 * model.geom_size[g])}"/></geometry>\n'
                         '    </collision>\n')
        inertial = inertial_xml(model.body_mass[b], model.body_ipos[b] - jpos,
                                model.body_iquat[b], model.body_inertia[b])
        links.append(f'  <link name="{name}">\n{inertial}{body}  </link>\n')
        if joint is None or ratios.get(joint) == 0.0:
            # No joint, or one the linkage keeps at zero (the couplers).
            joints.append(joint_xml(joint or f'{name}_mount', 'fixed', names[parent_id], name,
                                    origin, quat))
            continue
        limit = model.jnt_range[model.joint(joint).id]
        mimic = None if joint == ACTUATED else (ACTUATED, ratios[joint])
        joints.append(joint_xml(joint, 'revolute', names[parent_id], name, origin, quat,
                                axis=(1, 0, 0), limit=limit, effort=5, velocity=2,
                                mimic=mimic))


def write_rig_urdf(ratios: dict[str, float]) -> None:
    """Carriage + hand as one fixed-base articulation for Isaac's URDF importer."""
    model = mujoco.MjModel.from_xml_path(str(GRIPPER))
    ur_dir = '../third_party/mujoco_menagerie/universal_robots_ur10e/assets'
    materials = ''.join(f'  <material name="{k}"><color rgba="{vec(v)}"/></material>\n'
                        for k, v in {**MATERIALS, 'carriage': (0.3, 0.32, 0.35, 1)}.items())
    links, joints = [], []

    def link(name, body='', extra_inertial=None):
        inertial = extra_inertial or inertial_xml(1e-3, (0, 0, 0), (1, 0, 0, 0), (1e-7,) * 3)
        links.append(f'  <link name="{name}">\n{inertial}{body}  </link>\n')

    # The carriage: world X, then world Z, then the hand's side-grasp tilt.
    link('rig_base')
    link('reach_link', extra_inertial=inertial_xml(CARRIAGE_MASS, (0, 0, 0), (1, 0, 0, 0), (0.01,) * 3))
    link('lift_link', extra_inertial=inertial_xml(CARRIAGE_MASS, (0, 0, 0), (1, 0, 0, 0), (0.01,) * 3))
    joints.append(joint_xml('reach', 'prismatic', 'rig_base', 'reach_link', axis=(1, 0, 0),
                            limit=REACH_RANGE, effort=200, velocity=0.5))
    joints.append(joint_xml('lift', 'prismatic', 'reach_link', 'lift_link', axis=(0, 0, 1),
                            limit=LIFT_RANGE, effort=200, velocity=0.5))

    stub_z = STUB_TOP - STUB_LENGTH / 2
    stub = ('    <visual>\n'
            f'      <origin xyz="0 0 {num(stub_z)}" rpy="0 0 0"/>\n'
            f'      <geometry><cylinder radius="{num(STUB_RADIUS)}" length="{num(STUB_LENGTH)}"/></geometry>\n'
            '      <material name="linkgray"/>\n'
            '    </visual>\n'
            '    <visual>\n'
            f'      <origin xyz="0 0 {num(STUB_TOP - RING_HEIGHT / 2)}" rpy="0 0 0"/>\n'
            f'      <geometry><cylinder radius="{num(STUB_RADIUS + 0.001)}" length="{num(RING_HEIGHT)}"/></geometry>\n'
            '      <material name="urblue"/>\n'
            '    </visual>\n')
    link('ur10e_hand', stub, inertial_xml(STUB_MASS, (0, 0, stub_z), (1, 0, 0, 0), (0.002, 0.002, 0.001)))
    joints.append(joint_xml('hand_mount', 'fixed', 'lift_link', 'ur10e_hand',
                            quat=hand_mount_quat()))

    wpos, wquat = wrist3_pose()
    ipos, iquat = wrist3_inertial()
    link('wrist_3_link', mesh_visual(f'{ur_dir}/wrist3.obj', 'linkgray', wpos, wquat),
         inertial_xml(WRIST3_MASS, ipos, iquat, WRIST3_INERTIA))
    joints.append(joint_xml('wrist_3_joint', 'revolute', 'ur10e_hand', 'wrist_3_link',
                            axis=(0, 0, 1), limit=(-2 * math.pi, 2 * math.pi), effort=56,
                            velocity=3.14))

    gripper_urdf(model, ratios, 'wrist_3_link', links, joints)

    RIG_URDF.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- {HEADER} -->\n'
        '<!-- The UR10e hand on a two-axis carriage, for Isaac\'s URDF importer (fix the\n'
        f'     base). The 2F-85 is actuated at {ACTUATED} (0 open .. 0.8 closed); every\n'
        '     other finger joint mimics it, and the couplers are fixed. See the generator. -->\n'
        '<robot name="hand_pick_rig">\n'
        '  <!-- Hints for MuJoCo\'s URDF loader; ignored by every other importer. -->\n'
        '  <mujoco>\n'
        '    <compiler discardvisual="false" fusestatic="false"/>\n'
        '  </mujoco>\n\n'
        f'{materials}\n' + ''.join(links) + '\n' + ''.join(joints) + '</robot>\n')


def write_bottle_urdf() -> None:
    """The amber bottle as a free rigid body, mass and inertia as MuJoCo has them."""
    spec = mujoco.MjSpec.from_file(str(BOTTLE_DIR / f'{BOTTLE}.xml'))
    spec.body(BOTTLE).add_freejoint()
    model = spec.compile()
    b = model.body(BOTTLE).id
    body = ''
    for g in range(model.body_geomadr[b], model.body_geomadr[b] + model.body_geomnum[b]):
        mesh = model.mesh(model.geom_dataid[g]).name
        material = f'{BOTTLE}_{g}'
        body += (f'    <visual>\n'
                 f'      <geometry><mesh filename="{mesh}.obj"/></geometry>\n'
                 f'      <material name="{material}"><color rgba="{vec(model.geom_rgba[g])}"/></material>\n'
                 f'    </visual>\n'
                 f'    <collision>\n'
                 f'      <geometry><mesh filename="{mesh}.obj"/></geometry>\n'
                 f'    </collision>\n')
    BOTTLE_URDF.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- {HEADER} -->\n'
        f'<!-- {BOTTLE}.xml as a URDF: one free rigid body, origin bottom-centre, +Z up.\n'
        '     The meshes collide as convex hulls, as in MuJoCo. -->\n'
        f'<robot name="{BOTTLE}">\n'
        f'  <link name="{BOTTLE}">\n'
        + inertial_xml(model.body_mass[b], model.body_ipos[b], model.body_iquat[b],
                       model.body_inertia[b])
        + body + '  </link>\n</robot>\n')


def main() -> None:
    ratios = mimic_ratios()
    for name, ratio in ratios.items():
        print(f'  {name}: {ratio:+.4f} x {ACTUATED}')
    write_hand_mjcf()
    write_scene_mjcf()
    write_rig_urdf(ratios)
    write_bottle_urdf()
    for path in (HAND_XML, SCENE_XML, RIG_URDF, BOTTLE_URDF):
        mujoco.MjModel.from_xml_path(str(path))   # every file must at least load
        print(f'wrote {path.relative_to(SIM)}')


if __name__ == '__main__':
    main()
