def check_kinematics(model: mujoco.MjModel, tree: list[dict], fx: float) -> None:
    """MuJoCo's forward kinematics of the scene against iris_pipette_rig.fk at
    the states the sequence passes through.

    Raises:
        RuntimeError: If a site or body is off by more than a micrometre.
    """
    data = mujoco.MjData(model)
    worst = 0.0
    for n in (3, 6, 8, 10, 13):
        state, _ = plan.state_at(plan.step_end(n) - 1e-6)
        joints = rig.joint_values(state)
        for name, q in joints.items():
            data.qpos[model.joint(name).qposadr[0]] = q
        mujoco.mj_kinematics(model, data)
        root = {'wrist_3_link': (np.array([fx, 0, rig.GRIP_Z + state['lift_z']]), np.array(rig.TOOL_QUAT))}
        poses = rig.fk(tree, joints, root)
        for name in ('pipette_tip', 'cap_seat'):
            worst = max(worst, float(np.linalg.norm(data.site(name).xpos - poses[name][0])))
        for name in ('pipette_swing', 'blade_3', 'clamp_mount'):
            worst = max(worst, float(np.linalg.norm(data.body(name).xpos - poses[name][0])))
    print(f'MuJoCo kinematics vs iris_pipette_rig.fk: within {worst * 1e6:.2f} um')
    if worst > 1e-6:
        raise RuntimeError('the MJCF and the rig tree disagree')


def check_urdf_kinematics(model: mujoco.MjModel, tree: list[dict], fx: float) -> None:
    """The URDF, loaded in MuJoCo, against iris_pipette_rig.fk: every joint set
    (the mimicked ones too), the bodies must sit where the tree puts them.

    Raises:
        RuntimeError: If a body is off by more than 10 um (the URDF's numbers
            are written to six significant digits).
    """
    data = mujoco.MjData(model)
    worst = 0.0
    for n in (3, 6, 8, 10, 13):
        state, _ = plan.state_at(plan.step_end(n) - 1e-6)
        joints = rig.joint_values(state)
        for name, q in joints.items():
            data.qpos[model.joint(name).qposadr[0]] = q
        mujoco.mj_kinematics(model, data)
        root = {'wrist_3_link': (np.array([fx, 0, rig.GRIP_Z + state['lift_z']]), np.array(rig.TOOL_QUAT))}
        poses = rig.fk(tree, joints, root)
        for name in ('pipette_swing', 'pipette_plunger', 'blade_3', 'planet_1', 'clamp_mount', 'carrier'):
            worst = max(worst, float(np.linalg.norm(data.body(name).xpos - poses[name][0])))
    print(f'URDF kinematics vs iris_pipette_rig.fk: within {worst * 1e6:.2f} um')
    if worst > 1e-5:
        raise RuntimeError('the URDF and the rig tree disagree')


