def mjcf_geom(g: dict, indent: str) -> str:
    attrs = [f'name="{g["name"]}"', f'pos="{vec(g["pos"])}"']
    if not np.allclose(g['quat'], (1, 0, 0, 0)):
        attrs.append(f'quat="{vec(g["quat"])}"')
    if g['type'] == 'mesh':
        attrs += ['type="mesh"', f'mesh="{g["mesh"].replace("/", "_")}"']
    elif g['type'] == 'cone':
        attrs += ['type="mesh"', 'mesh="cone_locator"']
    else:
        attrs += [f'type="{g["type"]}"', f'size="{vec(g["size"])}"']
    if g['collide']:
        contype, conaffinity = COLLIDE[g['collide']]
        attrs += [f'contype="{contype}"', f'conaffinity="{conaffinity}"', 'group="3"', 'rgba="0.8 0.3 0.3 0.3"']
    else:
        attrs += ['contype="0"', 'conaffinity="0"', 'group="2"', f'material="{g["material"]}"']
    if g['mass'] is not None:
        attrs.append(f'mass="{num(g["mass"])}"')
    return f'{indent}<geom {" ".join(attrs)}/>\n'


def mjcf_body(b: dict, children: dict, indent: str) -> str:
    attrs = f'name="{b["name"]}" pos="{vec(b["pos"])}"'
    if not np.allclose(b['quat'], (1, 0, 0, 0)):
        attrs += f' quat="{vec(b["quat"])}"'
    out = f'{indent}<body {attrs}>\n'
    if b['mass'] is not None:
        out += f'{indent}  <inertial pos="0 0 0" mass="{num(b["mass"])}" diaginertia="1e-6 1e-6 1e-6"/>\n'
    j = b['joint']
    if j is not None:
        rng = '' if j['range'] is None else f' range="{vec(j["range"])}"'
        out += f'{indent}  <joint name="{j["name"]}" type="{j["type"]}" axis="{vec(j["axis"])}"{rng} armature="0.001" damping="0.05"/>\n'
    for g in b['geoms']:
        out += mjcf_geom(g, indent + '  ')
    for s in b['sites']:
        out += f'{indent}  <site name="{s["name"]}" pos="{vec(s["pos"])}" size="0.003" rgba="0.9 0.3 0.1 0.5" group="4"/>\n'
    for c in children.get(b['name'], []):
        out += mjcf_body(c, children, indent + '  ')
    return out + f'{indent}</body>\n'


