def write_stl(path, triangles: np.ndarray) -> None:
    tris = np.asarray(triangles, np.float32)
    normals = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-12)
    record = np.dtype([('normal', '<f4', 3), ('v', '<f4', (3, 3)), ('attr', '<u2')])
    data = np.zeros(len(tris), record)
    data['normal'], data['v'] = normals, tris
    path.write_bytes(b'\0' * 80 + struct.pack('<I', len(tris)) + data.tobytes())


def cone_stl(radius: float, half_height: float, n: int = 24) -> np.ndarray:
    """A cone centred on its axis, apex at +Z, like three.js's ConeGeometry."""
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    ring = np.stack([radius * np.cos(a), radius * np.sin(a), np.full(n, -half_height)], 1)
    nxt = np.roll(ring, -1, axis=0)
    apex, base = np.array([0, 0, half_height]), np.array([0, 0, -half_height])
    sides = np.stack([ring, nxt, np.tile(apex, (n, 1))], 1)
    bottom = np.stack([nxt, ring, np.tile(base, (n, 1))], 1)
    return np.concatenate([sides, bottom])


def mesh_file(key: str) -> str:
    """'iris/body' -> 'iris_body.stl'."""
    return key.replace('/', '_') + '.stl'


def write_meshes() -> None:
    MESH_DIR.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(rig.IRIS_ZIP) as archive:
        for part in rig.IRIS_PARTS:
            (MESH_DIR / mesh_file(f'iris/{part}')).write_bytes(rig.zip_member(archive, f'meshes/{part}.stl'))
    for part in ('glass', 'cap'):
        write_stl(MESH_DIR / mesh_file(f'amber/{part}'), rig.amber_mesh(part))
    with zipfile.ZipFile(rig.PIPETTE_ZIP) as archive:
        for parts in rig.PIPETTE_PARTS.values():
            for part in parts:
                (MESH_DIR / mesh_file(f'pipette/{part}')).write_bytes(rig.zip_member(archive, f'meshes/{part}.stl'))
    (cone,) = [g for b in rig.tree(-0.15) for g in b['geoms'] if g['type'] == 'cone']
    write_stl(MESH_DIR / 'cone_locator.stl', cone_stl(*cone['size']))


