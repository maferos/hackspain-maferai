def bottle_collision() -> list[tuple[str, tuple, tuple, tuple]]:
    """The amber bottle, hollow, as (type, pos, quat, size): its floor, a ring
    of wall boxes up the straight body and a ring of neck boxes around the
    bore. The shoulder between them is left open: nothing reaches it."""
    a = rig.AMBER
    R, wall, floor = a['r'], a['wall'], a['floor']
    shapes = [('cylinder', (0, 0, floor / 2), (1, 0, 0, 0), (R - wall, floor / 2))]
    for n, r_out, r_in, z0, z1 in ((16, R, R - wall, floor, a['shoulder']),
                                   (8, a['neck_r'], a['bore'], a['neck'], a['h'])):
        r_mid, t = (r_out + r_in) / 2, r_out - r_in
        half_w = r_in * math.tan(math.pi / n)
        for k in range(n):
            a = k * 2 * math.pi / n
            shapes.append(('box', (r_mid * math.cos(a), r_mid * math.sin(a), (z0 + z1) / 2), rig.zrot(a),
                           (t / 2, half_w, (z1 - z0) / 2)))
    return shapes


