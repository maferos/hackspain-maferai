def build_bottle(root, J):
    """The reference bottle, its liquid and the cap, carried as the page carries them."""
    bottle = part('bottle', None, lathe(bottle_profile(B)), 'bottle')
    part('liquid', bottle, lathe([(0, 2.6), (B['r'] - 2.6, 2.6), (B['r'] - 2.6, B['level']), (0, B['level'])], 48), 'liquid')
    cap = part('cap', None, lathe(cap_profile(B), 64), 'cap')
    c = B['cap_r']
    for k in range(24):
        a = k * TAU / 24
        part(f'cap_rib_{k}', cap, box(-0.5, 0.5, -0.5, 0.5, 0, B['cap_h'] - 3.5), 'cap',
             pos=((c - 0.4) * math.cos(a), (c - 0.4) * math.sin(a), 1.5), yaw=a)
    # held: in the hand frame (the origins coincide when the bottle stands on the table)
    hold = child_of(bottle, J['hand'])
    add_driver(hold, 'influence', -1, root, 'grip_aperture', f'1 if a <= {2 * rig.vertex(B["r"]) * MM + 0.3 * MM:.6g} else 0')
    neck = empty('cap_on_bottle', bottle, (0, 0, B['cap_z'] * MM), size=0.008)
    for target, expr in ((neck, '1 if a <= 1e-4 else 0'), (bpy.data.objects['cap_seat'], '1 if a > 1e-4 else 0')):
        add_driver(child_of(cap, target), 'influence', -1, root, 'housing_turns', expr)
    return bottle, cap


def add_drivers(root, J):
    for b in rig.LINKS:
        j, obj = b['joint'], J[b['name']]
        (axis,) = np.flatnonzero(j['axis'])
        sign = float(np.sign(j['axis'][axis]))
        expr = f'{sign * j["coef"]:.9g} * a'
        if j['type'] == 'slide':
            obj.lock_location = (True, True, True)
            add_driver(obj, 'location', int(axis), root, j['prop'], expr)
        else:
            obj.lock_rotation = (True, True, True)
            add_driver(obj, 'rotation_euler', int(axis), root, j['prop'], expr)


def set_state(root, state):
    for k in rig.STATE:
        root[k] = float(state[k])
    root['fill'] = float(state.get('fill', 0.0))
    root.update_tag()              # a property set from Python does not tag the drivers by itself
    for obj in bpy.data.objects:
        if obj.constraints:
            obj.update_tag()
    bpy.context.view_layer.update()


def keyframe_sequence(root, scene):
    frames = rig.keys(B)
    (t_prev, prev), (t_last, last) = frames[-2], frames[-1]
    mid = dict(prev)
    mid['grip_aperture'] = last['grip_aperture']
    frames = frames[:-1] + [((t_prev + t_last) / 2, mid), (t_last, last)]
    for t, state in frames:
        frame = 1 + round(t * FPS)
        for k in (*rig.STATE, 'fill'):
            root[k] = float(state[k])
            root.keyframe_insert(f'["{k}"]', frame=frame)
    scene.frame_start, scene.frame_end = 1, 1 + round((rig.DURATION + rig.TAIL) * FPS)
    scene.render.fps = FPS
    try:
        action = root.animation_data.action
        fcurves = getattr(action, 'fcurves', None)
        if fcurves is None or not len(fcurves):     # slotted actions (Blender >= 4.4)
            fcurves = [f for layer in action.layers for strip in layer.strips
                       for bag in strip.channelbags for f in bag.fcurves]
        for fcurve in fcurves:
            for kp in fcurve.keyframe_points:
                kp.interpolation, kp.easing = 'SINE', 'EASE_IN_OUT'
    except Exception as exc:   # noqa: BLE001 - the file is still right, only the easing differs
        print(f'could not set the easing: {exc}')
    set_state(root, frames[0][1])
    scene.frame_set(1)


