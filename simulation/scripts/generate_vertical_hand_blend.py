def bottle_collision():
    """The bottle as a hollow shell MuJoCo can collide with: a floor disc, a ring of wall boxes up the
    straight body and a ring of neck boxes around the bore; the shoulder is left open, nothing reaches it."""
    ct, ca = COLLIDE['bottle']
    common = f'contype="{ct}" conaffinity="{ca}" group="3" rgba="0.8 0.3 0.3 0.3" mass="0"'
    out = f'      <geom name="bottle_floor" type="cylinder" pos="0 0 {num(1.25 * MM)}" size="{num(B["r"] * MM)} {num(1.25 * MM)}" {common}/>\n'
    for kind, n, r_out, thick, z0, z1 in (('wall', 24, B['r'], 2.0, 2.5, B['shoulder']), ('neck', 12, B['neck_r'], 2.0, B['neck'], B['h'])):
        half_t, rc, half_w, hz, zc = thick / 2, r_out - thick / 2, r_out * math.tan(math.pi / n), (z1 - z0) / 2, (z0 + z1) / 2
        for k in range(n):
            a = k * TAU / n
            out += (f'      <geom name="bottle_{kind}_{k}" type="box" pos="{vec((rc * math.cos(a) * MM, rc * math.sin(a) * MM, zc * MM))}" '
                    f'quat="{vec(rig.quat_z(a))}" size="{vec((half_t * MM, half_w * MM, hz * MM))}" {common}/>\n')
    return out


def home_keyframe(model):
    data = mujoco.MjData(model)
    for name, q in rig.joints(rig.start(B)).items():
        data.qpos[model.joint(name).qposadr[0]] = q
    data.qpos[model.joint('bottle').qposadr[0]:][:7] = (0, 0, 0, 1, 0, 0, 0)
    data.qpos[model.joint('cap').qposadr[0]:][:7] = (0, 0, B['cap_z'] * MM, 1, 0, 0, 0)
    ctrl = [rig.joints(rig.start(B))[model.actuator(a).name] for a in range(model.nu)]
    return (f'\n  <keyframe>\n    <key name="home" qpos="{vec(data.qpos)}" ctrl="{vec(ctrl)}"/>\n  </keyframe>\n')


def urdf_origin(pos, yaw=0.0):
    return f'<origin xyz="{vec(pos)}" rpy="0 0 {num(yaw)}"/>'


def write_urdf(meshes):
    out = f'<?xml version="1.0"?>\n<!-- {HEADER} -->\n<!-- The vertical uncap-and-pipette hand for Isaac Lab\'s URDF importer: the tree of\n     vertical_hand.xml, followers as mimic joints. Root link vertical_hand; fix it to the world. -->\n<robot name="vertical_hand">\n'
    for m in sorted({mat for b in rig.LINKS for _, mat in meshes.get(b['name'], [])}):
        out += f'  <material name="{m}"><color rgba="{rgba(m)}"/></material>\n'
    out += '  <link name="vertical_hand"/>\n'
    for b in rig.LINKS:
        m = b['mass']
        out += f'  <link name="{b["name"]}">\n'
        out += (f'    <inertial><origin xyz="0 0 0"/><mass value="{num(m)}"/>'
                f'<inertia ixx="{num(max(1e-6, m * 2e-4))}" iyy="{num(max(1e-6, m * 2e-4))}" izz="{num(max(1e-6, m * 2e-4))}" ixy="0" ixz="0" iyz="0"/></inertial>\n')
        for name, mat in meshes.get(b['name'], []):
            out += (f'    <visual><origin xyz="0 0 0"/><geometry><mesh filename="meshes/{name}.stl"/></geometry>'
                    f'<material name="{mat}"/></visual>\n')
        for kind, pos, yaw, size, _ in collision_geoms(b['name']):
            if kind == 'box':
                shape = f'<box size="{vec([2 * s for s in size])}"/>'
            else:
                shape = f'<cylinder radius="{num(size[0])}" length="{num(2 * size[1])}"/>'
            out += f'    <collision>{urdf_origin(pos, yaw)}<geometry>{shape}</geometry></collision>\n'
        out += '  </link>\n'
    for b in rig.LINKS:
        j, name = b['joint'], rig.joint_name(b['name'])
        parent = 'vertical_hand' if b['parent'] is None else b['parent']
        typ = 'prismatic' if j['type'] == 'slide' else 'revolute'
        force = GAINS.get(name, (0, 0, 20.0))[2]
        out += f'  <joint name="{name}" type="{typ}">\n'
        out += f'    <parent link="{parent}"/><child link="{b["name"]}"/>\n'
        out += f'    {urdf_origin(b["pos"], b["yaw"])}\n    <axis xyz="{vec(j["axis"])}"/>\n'
        out += f'    <limit lower="{num(j["range"][0])}" upper="{num(j["range"][1])}" effort="{num(force)}" velocity="{2.0 if typ == "prismatic" else 10.0}"/>\n'
        if b['name'] in rig.FOLLOWS:
            leader, k = rig.FOLLOWS[b['name']]
            out += f'    <mimic joint="{leader}" multiplier="{num(k)}" offset="0"/>\n'
        out += '  </joint>\n'
    out += '</robot>\n'
    URDF.write_text(out)


# ============================== checks ==============================
def check_states():
    for n in CHECK_STEPS:
        state, _ = rig.state_at(rig.step_end(n) - 1e-6)
        yield n, state, rig.fk(state)


def check_blender(root, sites, bottle, cap):
    worst = 0.0
    for n, state, want in check_states():
        set_state(root, state)
        for name, obj in sites.items():
            err = float((Vector(want[name]) - obj.matrix_world.translation).length)
            worst = max(worst, err)
            if err > 1e-6:
                print(f'  blend, step {n}: {name} off by {err * 1000:.4f} mm')
        # the bottle and the cap, where the page's rule puts them
        held, in_clamp = rig.attachments(state, B)
        bottle_want = np.array([0, 0, state['lift_z'] if held else 0.0])
        cap_want = want['cap_seat'] if in_clamp else bottle_want + [0, 0, B['cap_z'] * MM]
        for name, obj, exp in (('bottle', bottle, bottle_want), ('cap', cap, cap_want)):
            err = float((Vector(exp) - obj.matrix_world.translation).length)
            worst = max(worst, err)
            if err > 1e-6:
                print(f'  blend, step {n}: {name} off by {err * 1000:.4f} mm (held {held}, in clamp {in_clamp})')
    print(f'.blend against fk: worst {worst * 1e6:.3f} um over steps {CHECK_STEPS}')
    if worst > 1e-6:
        raise RuntimeError('the .blend disagrees with vertical_hand_rig.fk')


def check_mjcf(path):
    model = mujoco.MjModel.from_xml_path(str(path))
    data = mujoco.MjData(model)
    worst = 0.0
    for n, state, want in check_states():
        for name, q in rig.joints(state).items():
            data.qpos[model.joint(name).qposadr[0]] = q
        mujoco.mj_kinematics(model, data)
        for name in rig.SITES:
            err = float(np.linalg.norm(data.site_xpos[model.site(name).id] - want[name]))
            worst = max(worst, err)
            if err > 1e-6:
                print(f'  mjcf, step {n}: {name} off by {err * 1000:.4f} mm')
    print(f'{path.name} against fk: worst {worst * 1e6:.3f} um; {model.nbody} bodies, {model.njnt} joints, {model.nu} actuators, {model.neq} equalities')
    if worst > 1e-6:
        raise RuntimeError(f'{path.name} disagrees with vertical_hand_rig.fk')


def check_urdf():
    model = mujoco.MjModel.from_xml_path(str(URDF))
    data = mujoco.MjData(model)
    worst = 0.0
    for n, state, want in check_states():
        for name, q in rig.joints(state).items():
            data.qpos[model.joint(name).qposadr[0]] = q
        mujoco.mj_kinematics(model, data)
        for name, (link, pos) in rig.SITES.items():
            b = model.body(link).id
            got = data.xpos[b] + data.xmat[b].reshape(3, 3) @ np.array(pos)
            err = float(np.linalg.norm(got - want[name]))
            worst = max(worst, err)
            if err > 1e-6:
                print(f'  urdf, step {n}: {name} off by {err * 1000:.4f} mm')
    print(f'{URDF.name} (loaded in MuJoCo) against fk: worst {worst * 1e6:.3f} um; {model.njnt} joints, {model.neq} mimic equalities')
    if worst > 1e-6:
        raise RuntimeError('the URDF disagrees with vertical_hand_rig.fk')
    if model.neq != len(rig.FOLLOWS):
        print(f'  note: MuJoCo turned {model.neq} of the {len(rig.FOLLOWS)} <mimic> tags into equalities')


