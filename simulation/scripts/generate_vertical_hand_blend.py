def main() -> None:
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = 'METRIC'
    scene.unit_settings.length_unit = 'MILLIMETERS'

    root = empty('vertical_hand', size=0.03)
    for k, (default, lo, hi, subtype, desc) in rig.PROPS.items():
        root[k] = float(default)
        ui = root.id_properties_ui(k)
        ui.update(min=lo, max=hi, soft_min=lo, soft_max=hi, description=desc, subtype=subtype)
    root['fill'] = 0.0
    root.id_properties_ui('fill').update(min=0.0, max=1.0, description='How full the tip is (render only)')
    root['steps'] = [name for name, _, _ in rig.STEPS]

    J = build_links(root)
    sites = build_hand(J)
    bottle, cap = build_bottle(root, J)

    # meshes and the simulator files come from the rest pose, before the drivers move anything
    meshes = export_meshes(J, {bottle, cap})
    n_tris = sum(1 for _ in MESH_DIR.glob('*.stl'))
    print(f'wrote {n_tris} STL meshes to {MESH_DIR.relative_to(SIM)}')
    write_hand_mjcf(meshes)
    write_scene_mjcf(meshes)
    write_scene_mjcf(meshes, home_keyframe(mujoco.MjModel.from_xml_path(str(SCENE_XML))))
    write_urdf(meshes)
    check_mjcf(HAND_XML)
    check_mjcf(SCENE_XML)
    check_urdf()

    add_drivers(root, J)
    check_blender(root, sites, bottle, cap)
    keyframe_sequence(root, scene)

    # a light, a world and a camera for renders
    sun = bpy.data.objects.new('sun', bpy.data.lights.new('sun', 'SUN'))
    sun.data.energy = 4
    sun.rotation_euler = (0.6, 0.3, 0.8)
    scene.collection.objects.link(sun)
    cam = bpy.data.objects.new('camera', bpy.data.cameras.new('camera'))
    cam.location, cam.rotation_euler = (0.75, -0.7, 0.55), (1.25, 0, 0.8)
    scene.collection.objects.link(cam)
    scene.camera = cam
    world = bpy.data.worlds.new('world')
    world.color = (0.35, 0.35, 0.38)
    scene.world = world

    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND), check_existing=False)
    BLEND.with_suffix('.blend1').unlink(missing_ok=True)
    glb = BLEND.with_suffix('.glb')
    bpy.ops.export_scene.gltf(filepath=str(glb), export_format='GLB', export_yup=True, export_apply=True,
                              export_animations=True, export_animation_mode='SCENE', export_extras=True)
    usd = BLEND.with_suffix('.usdc')
    try:
        bpy.ops.wm.usd_export(filepath=str(usd), export_animation=True, export_materials=True, root_prim_path='/vertical_hand')
    except Exception as exc:   # noqa: BLE001
        print(f'USD export failed: {exc}')
    for f in (BLEND, glb, usd, HAND_XML, SCENE_XML, URDF):
        if f.exists():
            print(f'wrote {f.relative_to(SIM)} ({f.stat().st_size / 1e6:.2f} MB)')

    # It has to come back with its properties.
    bpy.ops.wm.open_mainfile(filepath=str(BLEND))
    root = bpy.data.objects['vertical_hand']
    missing = [k for k in rig.PROPS if k not in root]
    if missing:
        raise RuntimeError(f'properties lost on save: {missing}')
    print(f'{BLEND.name} reopens with {len(rig.PROPS)} properties, {bpy.context.scene.frame_end} frames')


if __name__ == '__main__':
    main()
