def srgb_to_linear(c):
    return tuple(((x + 0.055) / 1.055) ** 2.4 if x > 0.04045 else x / 12.92 for x in c)


def material(name):
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    rgb, metallic, roughness = MATERIALS[name]
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes['Principled BSDF']
    lin = srgb_to_linear(rgb)
    alpha = ALPHA.get(name, 1.0)
    bsdf.inputs['Base Color'].default_value = (*lin, 1.0)
    bsdf.inputs['Metallic'].default_value = metallic
    bsdf.inputs['Roughness'].default_value = roughness
    mat.diffuse_color = (*lin, alpha)
    if name == 'led':
        bsdf.inputs['Emission Color'].default_value = (*lin, 1.0)
        bsdf.inputs['Emission Strength'].default_value = 4.0
    if alpha < 1:
        bsdf.inputs['Alpha'].default_value = alpha
        try:
            mat.surface_render_method = 'BLENDED'
        except AttributeError:
            mat.blend_method = 'BLEND'
    return mat


def empty(name, parent=None, pos=(0, 0, 0), yaw=0.0, size=0.02):
    obj = bpy.data.objects.new(name, None)
    obj.empty_display_type = 'ARROWS'
    obj.empty_display_size = size
    bpy.context.scene.collection.objects.link(obj)
    obj.parent = parent
    obj.location = pos
    obj.rotation_mode = 'XYZ'
    obj.rotation_euler = (0, 0, yaw)
    return obj


def part(name, parent, mesh, mat, pos=(0, 0, 0), yaw=0.0, bevel=0.0, smooth_angle=35.0):
    """One mesh object (mm in, metres out) under a link, with sharp edges by angle."""
    verts, faces = mesh[0], mesh[1]
    if len(mesh) == 3:
        bevel = mesh[2]
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(c * MM for c in v) for v in verts], [], faces)
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-7)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    if bevel > 0:
        bmesh.ops.bevel(bm, geom=bm.edges[:], offset=bevel * MM, offset_type='OFFSET', segments=2, profile=0.5,
                        affect='EDGES', clamp_overlap=True)
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    for f in bm.faces:
        f.smooth = True
    for e in bm.edges:
        angle = e.calc_face_angle(None)
        e.smooth = angle is not None and angle < smooth_angle * DEG
    bm.to_mesh(me)
    bm.free()
    me.validate()
    me.update()
    me.materials.append(material(mat))
    obj = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(obj)
    obj.parent = parent
    obj.location = tuple(c * MM for c in pos)
    obj.rotation_mode = 'XYZ'
    obj.rotation_euler = (0, 0, yaw)
    return obj


def add_driver(obj, path, index, root, prop, expr):
    fcurve = obj.driver_add(path, index)
    driver = fcurve.driver
    driver.type = 'SCRIPTED'
    var = driver.variables.new()
    var.name = 'a'
    var.type = 'SINGLE_PROP'
    var.targets[0].id = root
    var.targets[0].data_path = f'["{prop}"]'
    driver.expression = expr


def child_of(obj, target):
    c = obj.constraints.new('CHILD_OF')
    c.target = target
    c.set_inverse_pending = False
    c.inverse_matrix = Matrix.Identity(4)
    return c


def build_links(root):
    """The joint tree: a mount empty at the pose and a joint empty under it, per link."""
    joints = {}
    for b in rig.LINKS:
        parent = root if b['parent'] is None else joints[b['parent']]
        mount = empty(f'{b["name"]}_mount', parent, b['pos'], b['yaw'], 0.01)
        j = joints[b['name']] = empty(b['name'], mount, size=0.015)
        j['joint'] = b['joint']['type']
        j['axis'] = list(b['joint']['axis'])
        j['range'] = list(b['joint']['range'])
        j['coupling'] = f'{rig.joint_name(b["name"])} = {b["joint"]["coef"]:.6g} * {b["joint"]["prop"]}'
    return joints


