def write_stl(path, triangles):
    tris = np.asarray(triangles, np.float32)
    normals = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-12)
    record = np.dtype([('normal', '<f4', 3), ('v', '<f4', (3, 3)), ('attr', '<u2')])
    data = np.zeros(len(tris), record)
    data['normal'], data['v'] = normals, tris
    path.write_bytes(b'\0' * 80 + struct.pack('<I', len(tris)) + data.tobytes())


def link_of(obj, J):
    """The joint link a mesh object hangs from."""
    links = set(J.values())
    o = obj
    while o is not None and o not in links:
        o = o.parent
    return o


def export_meshes(J, extra):
    """One STL per (link, material), in the link's joint frame, at the rest pose (all joints 0).

    Returns {link name: [(mesh name, material)]}; `extra` are free objects exported in their own frame.
    """
    MESH_DIR.mkdir(parents=True, exist_ok=True)
    for old in MESH_DIR.glob('*.stl'):
        old.unlink()
    bpy.context.view_layer.update()
    groups = {}
    for obj in bpy.data.objects:
        if obj.type != 'MESH':
            continue
        link = link_of(obj, J)
        if link is None:
            top = obj
            while top.parent is not None:
                top = top.parent
            if top not in extra:
                continue
            link = top
        groups.setdefault((link.name, obj.data.materials[0].name), []).append(obj)
    out = {}
    for (link_name, mat), objs in sorted(groups.items()):
        link = bpy.data.objects[link_name]
        tris = []
        for obj in objs:
            M = link.matrix_world.inverted() @ obj.matrix_world
            me = obj.data
            me.calc_loop_triangles()
            co = np.array([M @ v.co for v in me.vertices], np.float64)
            idx = np.array([t.vertices for t in me.loop_triangles], np.int64)
            tris.append(co[idx])
        name = f'{link_name}__{mat}'
        write_stl(MESH_DIR / f'{name}.stl', np.concatenate(tris))
        out.setdefault(link_name, []).append((name, mat))
    return out


def num(x):
    return f'{x:.6g}'


def vec(v):
    return ' '.join(num(float(x)) for x in v)


def rgba(mat):
    return vec((*MATERIALS[mat][0], ALPHA.get(mat, 1.0)))


def collision_geoms(link):
    """(kind, pos (m), yaw, size) primitives per link, MuJoCo style sizes (half sizes for boxes)."""
    if link in ('jaw_l', 'jaw_r'):
        return [('box', pos, yaw, half, 'pad') for pos, yaw, half in pad_boxes(1 if link == 'jaw_l' else -1)]
    if link.startswith('blade_'):
        return [('box', (IRIS['blade_w'] / 2 * MM, IRIS['blade_len'] / 2 * MM, IRIS['blade_t'] / 2 * MM), 0.0,
                 (IRIS['blade_w'] / 2 * MM, IRIS['blade_len'] / 2 * MM, IRIS['blade_t'] / 2 * MM), 'blade')]
    if link == 'pip_swing':
        # the tip and the shaft, as one cylinder up to the collar, in the held frame
        return [('cylinder', (-PIVOT['x'] * MM, -PIVOT['y'] * MM, (PIP['tip_len'] + PIP['shaft_len']) / 2 * MM), 0.0,
                 (PIP['shaft_r1'] * MM, (PIP['tip_len'] + PIP['shaft_len']) / 2 * MM), 'tip')]
    return []


def mjcf_body(b, children, meshes, indent):
    j = b['joint']
    attrs = f'name="{b["name"]}" pos="{vec(b["pos"])}"'
    if b['yaw']:
        attrs += f' quat="{vec(rig.quat_z(b["yaw"]))}"'
    out = f'{indent}<body {attrs}>\n'
    m = b['mass']
    out += f'{indent}  <inertial pos="0 0 0" mass="{num(m)}" diaginertia="{vec([max(1e-6, m * 2e-4)] * 3)}"/>\n'
    follower = b['name'] in rig.FOLLOWS      # light, so the leader's actuator does not fight the reflected inertia
    armature, damping = (1e-5, 0.01) if follower else (0.001, 0.5 if j['type'] == 'slide' else 0.02)
    out += (f'{indent}  <joint name="{rig.joint_name(b["name"])}" type="{j["type"]}" axis="{vec(j["axis"])}" '
            f'range="{vec(j["range"])}" armature="{armature}" damping="{damping}"/>\n')
    for name, mat in meshes.get(b['name'], []):
        out += f'{indent}  <geom name="{name}" type="mesh" mesh="{name}" material="{mat}" contype="0" conaffinity="0" group="2" mass="0"/>\n'
    for k, (kind, pos, yaw, size, who) in enumerate(collision_geoms(b['name'])):
        ct, ca = COLLIDE[who]
        quat = '' if not yaw else f' quat="{vec(rig.quat_z(yaw))}"'
        out += (f'{indent}  <geom name="{b["name"]}_col_{k}" type="{kind}" pos="{vec(pos)}"{quat} size="{vec(size)}" '
                f'contype="{ct}" conaffinity="{ca}" group="3" rgba="0.8 0.3 0.3 0.3" mass="0"/>\n')
    for name, (link, pos) in rig.SITES.items():
        if link == b['name']:
            out += f'{indent}  <site name="{name}" pos="{vec(pos)}" size="0.003" rgba="0.9 0.3 0.1 0.5" group="4"/>\n'
    for c in children.get(b['name'], []):
        out += mjcf_body(c, children, meshes, indent + '  ')
    return out + f'{indent}</body>\n'


